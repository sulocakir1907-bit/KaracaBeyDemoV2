// Helper function to format composition as string
export function formatComposition(composition: FabricComposition): string {
  const parts: string[] = []
  if (composition.cotton) parts.push(`${composition.cotton}% Cotton`)
  if (composition.polyester) parts.push(`${composition.polyester}% Polyester`)
  if (composition.viscose) parts.push(`${composition.viscose}% Viscose`)
  if (composition.silk) parts.push(`${composition.silk}% Silk`)
  if (composition.linen) parts.push(`${composition.linen}% Linen`)
  if (composition.wool) parts.push(`${composition.wool}% Wool`)
  if (composition.acrylic) parts.push(`${composition.acrylic}% Acrylic`)
  if (composition.nylon) parts.push(`${composition.nylon}% Nylon`)
  if (composition.metallic) parts.push(`${composition.metallic}% Metallic`)
  return parts.join(', ')
}

