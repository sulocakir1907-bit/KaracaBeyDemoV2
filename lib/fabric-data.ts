export interface FabricComposition {
  cotton?: number
  polyester?: number
  viscose?: number
  silk?: number
  linen?: number
  wool?: number
  acrylic?: number
  nylon?: number
  metallic?: number
}

export interface FabricProduct {
  id: string
  name: string
  category: FabricCategory
  sku: string
  width: number // in cm
  weight: number // in g/m² (GSM)
  composition: FabricComposition
  usageAreas: UsageArea[]
  washingInstructions: WashingInstruction[]
  colors: string[]
  pattern?: string
  finish?: string
  martindale?: number // abrasion resistance
  lightFastness?: number // 1-8 scale
  fireRetardant?: boolean
  images: {
    primary: string
    detail?: string
    styled?: string[]
  }
  minOrder: number // in meters
  priceCategory: 1 | 2 | 3 | 4 | 5 // $ to $$$$$
  featured?: boolean
  new?: boolean
  bestseller?: boolean
}

