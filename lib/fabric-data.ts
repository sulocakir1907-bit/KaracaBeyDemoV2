// Filter products with multiple criteria
export interface FilterCriteria {
  category?: FabricCategory
  usageArea?: UsageArea
  minWeight?: number
  maxWeight?: number
  minWidth?: number
  maxWidth?: number
  priceCategory?: number
  fireRetardant?: boolean
  search?: string
}

export function filterProducts(criteria: FilterCriteria): FabricProduct[] {
  return FABRIC_DATA.filter(product => {
    if (criteria.category && product.category !== criteria.category) return false
    if (criteria.usageArea && !product.usageAreas.includes(criteria.usageArea)) return false
    if (criteria.minWeight && product.weight < criteria.minWeight) return false
    if (criteria.maxWeight && product.weight > criteria.maxWeight) return false
    if (criteria.minWidth && product.width < criteria.minWidth) return false
    if (criteria.maxWidth && product.width > criteria.maxWidth) return false
    if (criteria.priceCategory && product.priceCategory !== criteria.priceCategory) return false
    if (criteria.fireRetardant && !product.fireRetardant) return false
    if (criteria.search) {
      const searchLower = criteria.search.toLowerCase()
      const matchesName = product.name.toLowerCase().includes(searchLower)
      const matchesSku = product.sku.toLowerCase().includes(searchLower)
      const matchesPattern = product.pattern?.toLowerCase().includes(searchLower)
      if (!matchesName && !matchesSku && !matchesPattern) return false
    }
    return true
  })
}
